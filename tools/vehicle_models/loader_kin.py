"""Quarry Days wheel loader - lift arm and bucket-tilt kinematics (Blender clips + scripts/art/loader_kin.gd).

Planar (y forward, z up, model space). The arms swing on the tower pivot; two lift cylinders (frame -> arm) raise them; one tilt cylinder
(arm -> bucket lug) rolls the bucket about the arm end. The articulated frame (steering) is separate: a rotation about the vertical hinge.
    python tools/vehicle_models/loader_kin.py     # prints ranges, writes scripts/art/loader_kin.gd
"""
import math, os

HINGE_Y = 0.05                     # centre articulation joint (y)
PIVOT = (0.30, 1.30)               # arm pivot on the tower (y, z)
BUCKET_PIVOT = (1.40, -0.90)       # bucket pin, arm-local
LIFT_MAX = 0.95                    # rad
TILT_MIN, TILT_MAX = -1.10, 0.90   # bucket angle relative to the arm (negative = curled back, positive = dump)
LIFT_BASE = (0.866, 0.438)         # lift cylinder base on the front frame (y, z)
LIFT_ROD = (1.294, -0.051)         # lift cylinder rod pin, arm-local
TILT_BASE = (0.007, 0.597)         # tilt cylinder base, arm-local
TILT_ROD = (0.184, 0.709)          # tilt cylinder rod pin, bucket-local
ARTIC_MAX = 0.55                   # rad of articulation at full lock
WHEEL_R = 0.55
ARM_X = 0.80                       # lift arm x (each side)
LIFT_X = 0.52                      # lift cylinder x


def rot(p, a):
    c, s = math.cos(a), math.sin(a)
    return (p[0] * c - p[1] * s, p[0] * s + p[1] * c)


def lift(alpha):
    r = rot(LIFT_ROD, alpha)
    dy, dz = PIVOT[0] + r[0] - LIFT_BASE[0], PIVOT[1] + r[1] - LIFT_BASE[1]
    return math.atan2(dz, dy), math.hypot(dy, dz)


def tilt(beta):
    """Tilt cylinder in the arm frame: (aim angle, length) from the arm base pin to the rod pin on the bucket."""
    r = rot(TILT_ROD, beta)
    dy, dz = BUCKET_PIVOT[0] + r[0] - TILT_BASE[0], BUCKET_PIVOT[1] + r[1] - TILT_BASE[1]
    return math.atan2(dz, dy), math.hypot(dy, dz)


def ranges(margin=0.02):
    ls = [lift(LIFT_MAX * i / 40)[1] for i in range(41)]
    ts = [tilt(TILT_MIN + (TILT_MAX - TILT_MIN) * i / 40)[1] for i in range(41)]
    return (min(ls) - margin, max(ls) + margin), (min(ts) - margin, max(ts) + margin)


def write_gd(path):
    (l0, l1), (t0, t1) = ranges()
    lines = [
        "extends RefCounted",
        "class_name LoaderKin",
        "## GENERATED by tools/vehicle_models/loader_kin.py - do not edit by hand. Wheel loader arm / bucket / articulation numbers (planar y, z).",
        "",
        "const PIVOT := Vector2(%.4f, %.4f)" % PIVOT,
        "const BUCKET_PIVOT := Vector2(%.4f, %.4f)" % BUCKET_PIVOT,
        "const LIFT_MAX := %.4f" % LIFT_MAX,
        "const TILT_MIN := %.4f" % TILT_MIN,
        "const TILT_MAX := %.4f" % TILT_MAX,
        "const LIFT_BASE := Vector2(%.4f, %.4f)" % LIFT_BASE,
        "const LIFT_ROD := Vector2(%.4f, %.4f)" % LIFT_ROD,
        "const TILT_BASE := Vector2(%.4f, %.4f)" % TILT_BASE,
        "const TILT_ROD := Vector2(%.4f, %.4f)" % TILT_ROD,
        "const ARTIC_MAX := %.4f" % ARTIC_MAX,
        "const WHEEL_R := %.4f" % WHEEL_R,
        "const LIFT_RANGE := Vector2(%.4f, %.4f)" % (l0, l1),
        "const TILT_RANGE := Vector2(%.4f, %.4f)" % (t0, t1),
        "",
        "static func rot(p: Vector2, a: float) -> Vector2:",
        "\tvar c := cos(a)",
        "\tvar s := sin(a)",
        "\treturn Vector2(p.x * c - p.y * s, p.x * s + p.y * c)",
        "",
        "## Lift cylinder: Vector2(aim angle about X, length) for arm angle alpha.",
        "static func lift(alpha: float) -> Vector2:",
        "\tvar w := PIVOT + rot(LIFT_ROD, alpha) - LIFT_BASE",
        "\treturn Vector2(atan2(w.y, w.x), w.length())",
        "",
        "## Tilt cylinder in the arm frame for a bucket angle beta (relative to the arm).",
        "static func tilt(beta: float) -> Vector2:",
        "\tvar w := BUCKET_PIVOT + rot(TILT_ROD, beta) - TILT_BASE",
        "\treturn Vector2(atan2(w.y, w.x), w.length())",
    ]
    open(path, "w", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    print("lift/tilt cylinder ranges", ranges(0.0))
    repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    write_gd(os.path.join(repo, "scripts", "art", "loader_kin.gd"))
    print("wrote scripts/art/loader_kin.gd")
