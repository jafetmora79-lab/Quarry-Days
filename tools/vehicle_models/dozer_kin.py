"""Quarry Days bulldozer - blade kinematics (Blender clips + scripts/art/dozer_kin.gd).

Lift: the C-frame (push arms + blade) swings about the trunnion on the track frames; two lift cylinders (planar y/z) push the arms up.
Tilt: the blade rolls about the forward axis at its pivot; one tilt cylinder (planar x/z in the blade plane) between the C-frame brace and the blade.
    python tools/vehicle_models/dozer_kin.py      # prints ranges and writes scripts/art/dozer_kin.gd
"""
import math, os

TRUNNION = (0.25, 0.55)            # lift axis (y, z), model space
ARM_LEN = 2.30                     # trunnion -> blade pivot along the arms
LIFT_MIN, LIFT_MAX = -0.12, 0.50   # rad: negative cuts below the ground, positive raises the blade
LIFT_BASE = (0.596, 0.30)          # lift cylinder base pin on the track frame (y, z)
LIFT_ROD = (1.032, 0.313)          # rod pin on the arm, arm-local (y, z)
TILT_MAX = 0.17                    # rad each way
TILT_BASE = (0.931, 0.992)         # tilt cylinder base (x, z) in the C-frame, blade-pivot coordinates at zero tilt
TILT_ROD = (1.097, 0.268)          # rod pin on the blade (x, z), blade-local
ARM_X = 1.20                       # push arm x
CYL_X = 1.38                       # lift cylinder x (outboard of the arms)
TRACK_V = 0.55                     # how much steering differences the two tracks (visual)


def rot(p, a):
    c, s = math.cos(a), math.sin(a)
    return (p[0] * c - p[1] * s, p[0] * s + p[1] * c)


def lift(alpha):
    """(angle, length) of a lift cylinder in the y/z plane for arm angle alpha."""
    r = rot(LIFT_ROD, alpha)
    w = (TRUNNION[0] + r[0], TRUNNION[1] + r[1])
    dy, dz = w[0] - LIFT_BASE[0], w[1] - LIFT_BASE[1]
    return math.atan2(dz, dy), math.hypot(dy, dz)


def tilt(theta):
    """(dx, dz, length) from the tilt base to the rod pin in the blade plane (rotation about the forward axis)."""
    c, s = math.cos(theta), math.sin(theta)
    rx, rz = TILT_ROD[0] * c + TILT_ROD[1] * s, -TILT_ROD[0] * s + TILT_ROD[1] * c
    dx, dz = rx - TILT_BASE[0], rz - TILT_BASE[1]
    return dx, dz, math.hypot(dx, dz)


def ranges(margin=0.02):
    ls = [lift(LIFT_MIN + (LIFT_MAX - LIFT_MIN) * i / 40)[1] for i in range(41)]
    ts = [tilt(-TILT_MAX + 2 * TILT_MAX * i / 40)[2] for i in range(41)]
    return (min(ls) - margin, max(ls) + margin), (min(ts) - margin, max(ts) + margin)


def write_gd(path):
    (l0, l1), (t0, t1) = ranges()
    lines = [
        "extends RefCounted",
        "class_name DozerKin",
        "## GENERATED by tools/vehicle_models/dozer_kin.py - do not edit by hand. Blade lift (y/z plane) and tilt (x/z plane) numbers.",
        "",
        "const TRUNNION := Vector2(%.4f, %.4f)" % TRUNNION,
        "const ARM_LEN := %.4f" % ARM_LEN,
        "const LIFT_MIN := %.4f" % LIFT_MIN,
        "const LIFT_MAX := %.4f" % LIFT_MAX,
        "const LIFT_BASE := Vector2(%.4f, %.4f)" % LIFT_BASE,
        "const LIFT_ROD := Vector2(%.4f, %.4f)" % LIFT_ROD,
        "const TILT_MAX := %.4f" % TILT_MAX,
        "const TILT_BASE := Vector2(%.4f, %.4f)" % TILT_BASE,
        "const TILT_ROD := Vector2(%.4f, %.4f)" % TILT_ROD,
        "const LIFT_RANGE := Vector2(%.4f, %.4f)" % (l0, l1),
        "const TILT_RANGE := Vector2(%.4f, %.4f)" % (t0, t1),
        "const TRACK_V := %.4f" % TRACK_V,
        "",
        "static func rot(p: Vector2, a: float) -> Vector2:",
        "\tvar c := cos(a)",
        "\tvar s := sin(a)",
        "\treturn Vector2(p.x * c - p.y * s, p.x * s + p.y * c)",
        "",
        "## Lift cylinder: Vector2(aim angle about X, length) for arm angle alpha.",
        "static func lift(alpha: float) -> Vector2:",
        "\tvar w := TRUNNION + rot(LIFT_ROD, alpha) - LIFT_BASE",
        "\treturn Vector2(atan2(w.y, w.x), w.length())",
        "",
        "## Tilt cylinder: Vector3(dx, dz, length) in the blade plane for tilt theta (rotation about the forward axis).",
        "static func tilt(theta: float) -> Vector3:",
        "\tvar c := cos(theta)",
        "\tvar s := sin(theta)",
        "\tvar rx := TILT_ROD.x * c + TILT_ROD.y * s",
        "\tvar rz := -TILT_ROD.x * s + TILT_ROD.y * c",
        "\tvar d := Vector2(rx - TILT_BASE.x, rz - TILT_BASE.y)",
        "\treturn Vector3(d.x, d.y, d.length())",
    ]
    open(path, "w", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    print("lift/tilt cylinder ranges", ranges(0.0))
    repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    write_gd(os.path.join(repo, "scripts", "art", "dozer_kin.gd"))
    print("wrote scripts/art/dozer_kin.gd")
