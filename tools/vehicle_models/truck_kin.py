"""Quarry Days dump truck - planar tipping-bed kinematics (y forward, z up). Single source for the Blender clips and the game's TruckRig.

    python tools/vehicle_models/truck_kin.py      # prints the ranges and writes scripts/art/truck_kin.gd
"""
import math, os

HINGE = (-2.15, 1.00)          # bed hinge at the rear, model space
RAM_BASE = (-1.50, 0.62)       # hydraulic cylinder base pin on the chassis cross-member
RAM_ROD = (2.20, -0.12)        # rod pin under the bed, bed-local
BED_MAX = 0.95                 # full tip (rad)
GATE_OPEN = -1.15              # tailgate swing (rad, negative = bottom swings rearward)
GATE_START, GATE_END = 0.16, 0.42   # bed tilt range over which the tailgate unlatches and swings open
WHEEL_R = 0.47
AXLES = {"F": 1.55, "R1": -0.85, "R2": -1.65}
STEER_MAX = 0.52               # front wheel lock (rad)
STEER_RATIO = 3.4              # steering wheel turns this many times the road wheel angle


def rot(p, a):
    c, s = math.cos(a), math.sin(a)
    return (p[0] * c - p[1] * s, p[0] * s + p[1] * c)


def ram(theta):
    """(angle, length) of the cylinder for bed tilt theta: aim from the base pin to the rod pin on the bed."""
    r = rot(RAM_ROD, theta)
    w = (HINGE[0] + r[0], HINGE[1] + r[1])
    dy, dz = w[0] - RAM_BASE[0], w[1] - RAM_BASE[1]
    return math.atan2(dz, dy), math.hypot(dy, dz)


def smooth(t):
    t = max(0.0, min(1.0, t))
    return t * t * (3 - 2 * t)


def gate(theta):
    return GATE_OPEN * smooth((theta - GATE_START) / (GATE_END - GATE_START))


def ram_range(margin=0.02):
    ds = [ram(BED_MAX * i / 40)[1] for i in range(41)]
    return min(ds) - margin, max(ds) + margin


def write_gd(path):
    lo, hi = ram_range()
    lines = [
        "extends RefCounted",
        "class_name TruckKin",
        "## GENERATED by tools/vehicle_models/truck_kin.py - do not edit by hand. Planar (y forward, z up) tipping-bed numbers.",
        "",
        "const HINGE := Vector2(%.4f, %.4f)" % HINGE,
        "const RAM_BASE := Vector2(%.4f, %.4f)" % RAM_BASE,
        "const RAM_ROD := Vector2(%.4f, %.4f)" % RAM_ROD,
        "const BED_MAX := %.4f" % BED_MAX,
        "const GATE_OPEN := %.4f" % GATE_OPEN,
        "const GATE_START := %.4f" % GATE_START,
        "const GATE_END := %.4f" % GATE_END,
        "const WHEEL_R := %.4f" % WHEEL_R,
        "const STEER_MAX := %.4f" % STEER_MAX,
        "const STEER_RATIO := %.4f" % STEER_RATIO,
        "const RAM_RANGE := Vector2(%.4f, %.4f)" % (lo, hi),
        "",
        "static func rot(p: Vector2, a: float) -> Vector2:",
        "\tvar c := cos(a)",
        "\tvar s := sin(a)",
        "\treturn Vector2(p.x * c - p.y * s, p.x * s + p.y * c)",
        "",
        "## Cylinder aim angle (about X) and length for a bed tilt.",
        "static func ram(theta: float) -> Vector2:",
        "\tvar w := HINGE + rot(RAM_ROD, theta) - RAM_BASE",
        "\treturn Vector2(atan2(w.y, w.x), w.length())",
        "",
        "## Tailgate angle for a bed tilt: latched until GATE_START, fully open by GATE_END.",
        "static func gate(theta: float) -> float:",
        "\tvar t := clampf((theta - GATE_START) / (GATE_END - GATE_START), 0.0, 1.0)",
        "\treturn GATE_OPEN * t * t * (3.0 - 2.0 * t)",
    ]
    open(path, "w", newline="\n").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    print("ram length range", ram_range(0.0))
    repo = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    write_gd(os.path.join(repo, "scripts", "art", "truck_kin.gd"))
    print("wrote scripts/art/truck_kin.gd")
