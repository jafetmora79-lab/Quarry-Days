    w("- `tools/repair_glb.py`: Quarry Days copies of the Veil props in `assets/veil_qd/` (the pack itself is untouched): geometry baked into one mesh, duplicate faces dropped, flush faces separated, collision hulls kept, materials still mapped, brushed metal made matte. `MeshKit.prop()` loads the copy when it exists.")
