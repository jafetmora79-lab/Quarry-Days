    w("## Per-asset table\n")
    w("| Asset | Source | Generator | Triangles | Materials | Defects before | Defects now | Change | Status |")
    w("|---|---|---|---|---|---|---|---|---|")
    for k in sorted(cur):
        c = cur[k]
        b = base.get(k, {})
        name = k.split("models/")[1]
        status = "clean" if not sev(c["defects"]) else "defects remain"
        change = NOTES.get(key_of(k), "generator repair pass" if (b.get("defects") != c["defects"] and "/procedural/" in k) else ("repaired copy" if "/veil/" in k and b.get("defects") != c["defects"] else "-"))
