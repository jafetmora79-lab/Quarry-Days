    w("## Summary\n")
    w("| | |\n|---|---|")
    w("| Models inspected | %d (%d Veil props, %d characters, %d generated) |" % (n_all, sum('/veil/' in k for k in cur), sum('/characters/' in k for k in cur), sum('/procedural/' in k for k in cur)))
    w("| Textures in the repo | %d |" % len(glob.glob(os.path.join(ROOT, "**", "*.png"), recursive=True)) if False else "| Materials / textures | %d .tres materials, %d .png textures (outside .godot) |" % (len(glob.glob(os.path.join(ROOT, "assets", "materials", "*.tres"))) + len(glob.glob(os.path.join(ROOT, "THE_VEIL_ASSETS_V2", "Materials_Godot", "**", "*.tres"), recursive=True)), len([p for p in glob.glob(os.path.join(ROOT, "**", "*.png"), recursive=True) if "/.godot/" not in p and "/docs/" not in p and "/veil_qd/" not in p])))
    w("| With a technical defect before | %d |" % sum(1 for v in base.values() if sev(v["defects"])))
    w("| With a technical defect now | %d |" % len(left))
    w("| Defect-free after repair | %d |" % len(fixed))
    w("| Assets whose geometry or generator changed | %d |" % len(changed))
    w("| Assets redesigned | 3 rebuilt in Phase A (repair-part hose, wall windows, compressor hose); the full redesign phases (B-E) are not done yet |")
    w("| Visually verified | 0 (UNVERIFIED) |\n")
    w("Defect kinds: `z_fighting` = faces of two materials on the same plane (flicker), `redundant_coplanar` = same-material overlap (wasteful, not visible), `duplicate_faces`, `degenerate_triangles`, `floating_parts` = disconnected geometry, `reversed_normals`, `missing_texture`, `shiny_metal`.\n")
    w("## Repairs made at the source (Phase A)\n")
    w("- `MeshKit.repair()` (scripts/art/mesh_kit.gd): drops degenerate/duplicate faces and separates every pair of coplanar faces that belong to different materials by growing the smaller part 4 mm - a real thickness, not a depth bias. It runs wherever a generator turns soups into meshes (vehicles, rigs, tools, machinery, buildings), is deterministic, and settles chains over several passes. Cost: about +0.1 s at start-up.")
