    w("- Generator fixes: windows, signs, truck glass/mirrors/guard, excavator glass, jaw-crusher flywheel shaft, output-storage ladder, compressor handle and hose, pneumatic-chisel hose, hand-splitter bolt and lever, repair-part hose.\n")
