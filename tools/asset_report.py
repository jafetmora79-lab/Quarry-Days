def generator(rel):
    parts = rel.split("/")
    if parts[1] == "procedural":
        cat = os.path.basename(rel).split("__")[0]
        if cat == "machinery":
            return "scripts/rig.gd" if "rig" in rel or "breaker" in rel else "scripts/art/quarry_art.gd"
        return GEN.get(cat, "?")
    if parts[1] == "veil":
        return "THE VEIL pack -> assets/veil_qd (tools/repair_glb.py)"
    return "imported glTF (assets/characters)"

def source(rel):
    if "/procedural/" in rel:
        return "tools/export_procedural_models.gd -> " + rel
    if "/veil/" in rel:
        return "THE_VEIL_ASSETS_V2/" + rel.split("/veil/")[1]
    return "assets/characters/" + os.path.basename(rel)

def key_of(rel):
    return os.path.splitext(os.path.basename(rel))[0]

def main():
    cur = json.load(open(os.path.join(DOCS, "audit", "asset_audit.json")))
    base = json.load(open(os.path.join(DOCS, "audit", "baseline_audit.json")))
    n_all = len(cur)
    def sev(d):
        return [x for x in d if not x.startswith(("shiny_metal", "redundant_coplanar"))]
    changed = [k for k in cur if base.get(k) and (base[k]["defects"] != cur[k]["defects"] or key_of(k) in NOTES)]
    fixed = [k for k in cur if base.get(k) and sev(base[k]["defects"]) and not sev(cur[k]["defects"])]
    left = [k for k in cur if sev(cur[k]["defects"])]
    out = []
    w = out.append
